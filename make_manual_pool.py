def parse_code_line(line: str) -> str:
    """从一行文本里提取 6 位股票代码"""
    line = line.strip().upper()
    if not line or line.startswith("#"):
        return ""
    # 去掉交易所后缀/前缀：600547.SH  sh600547  600547
    m = re.search(r"\b(\d{6})\b", line)
    if m:
        return m.group(1)
    return ""


def load_from_file(path: str) -> list:
    """从 codes.txt 逐行解析代码"""
    codes = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            c = parse_code_line(line)
            if c:
                codes.append(c)
    return codes


def build_dataframe(codes: list) -> pd.DataFrame:
    """生成 manual_pool.csv 的 DataFrame（最简版，其余字段实时补齐）"""
    seen = set()
    rows = []
    for c in codes:
        c6 = c.zfill(6)
        if c6 in seen:
            continue
        seen.add(c6)
        rows.append({
            "code": c6,
            # 以下留空 -> 由腾讯快照 / AkShare 自动补齐；
            # 若你在通达信里已有这些值，直接在这里加列即可生效。
            "name": "",
            "sw_l1": "", "sw_l2": "", "cycle": "none",
            "base_price": "",
            "profit_yoy": "", "rev_yoy": "", "roe": "",
            "gross_margin": "", "debt_ratio": "", "div_yield": "",
            "total_mv": "", "circ_mv": "", "free_circ_mv": "",
            "pb": "", "pe_static": "", "pe_ttm": "", "pe_dyn": "",
        })
    return pd.DataFrame(rows)


def main():
    parser = argparse.ArgumentParser(description="生成 manual_pool.csv（通达信 132 只慢池）")
    parser.add_argument("--from-file", default=None, help="从 codes.txt 导入代码（一行一只）")
    parser.add_argument("--out", default="manual_pool.csv", help="输出路径")
    args = parser.parse_args()

    if args.from_file:
        codes = load_from_file(args.from_file)
    else:
        codes = SAMPLE_CODES

    if not codes:
        print("=" * 60)
